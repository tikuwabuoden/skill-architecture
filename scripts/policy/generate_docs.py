#!/usr/bin/env python3
"""Generate the naming document from validated shared and local settings."""

from __future__ import annotations

import argparse
from pathlib import Path
import sys

from policy import PolicyError, compile_pattern, load_policy


def _code(value: str) -> str:
    # Configuration values are displayed literally, even if they contain backticks.
    delimiter = "`"
    while delimiter in value:
        delimiter += "`"
    return f"{delimiter} {value} {delimiter}" if "`" in value else f"`{value}`"


def render_document(policy: dict) -> str:
    names = [entry["name"] for entry in policy["types"]]
    scope = policy["scope"]
    lines = [
        "<!-- Generated by scripts/policy/generate_docs.py. Do not edit directly. -->",
        "# 命名規約", "",
        "共通設定と利用先設定から生成した文書です。機械検証の正本は設定ファイルです。", "",
        "## コミット件名・PRタイトル", "",
        "```text", "<type>(<scope>): <summary> (#<issue番号>)", "```", "",
        "- scopeを省略する場合は括弧も省略する。",
        "- 破壊的変更ではtypeまたはscopeの後、コロンの前に`!`を付ける。",
        "- summaryは空にせず、件名・タイトルを1行で記述する。",
        "- summary末尾に使えない文字: " + (
            "、".join(_code(value) for value in policy["summary_forbidden_endings"]) or "なし"),
        "- issue番号は正の整数。issueなしの場合は接尾辞を省略できる。", "",
        "### type", "",
    ]
    lines.extend(f"- `{entry['name']}`: {entry['description']}" for entry in policy["types"])
    lines.extend(["", "### scope", ""])
    allowed = scope["allowed"]
    lines.append("- 許可一覧: " + ("制限なし" if allowed is None else
                                    "、".join(_code(value) for value in allowed) or "scopeの指定不可"))
    requirement = "省略可能"
    if scope["required"]:
        requirement = "すべてのtypeで必須"
    elif scope["required_for_types"]:
        requirement = "、".join(_code(value) for value in scope["required_for_types"]) + "で必須"
    lines.append("- 必須条件: " + requirement)
    lines.extend([
        "", "## ブランチ名", "",
        "```text", "<type>/<issue番号>-<短い説明>", "<type>/no-issue-<短い説明>", "```", "",
        "- typeはコミット件名・PRタイトルと共通。scopeは含めない。",
        "- issue番号は正の整数とし、`#`は付けない。",
        "- 説明は英小文字・数字を使い、単語をハイフンで区切る。",
        "- 常設ブランチの例外: " + (
            "、".join(_code(value) for value in policy["permanent_branches"]) or "なし"),
        "", "## issue参照", "",
        "- コミットは現在のブランチ、PRは作成元ブランチの番号を使う。",
        "- 件名・タイトル末尾: " + _code(policy["issue_reference"]["subject_suffix"].replace("{issue}", "<issue番号>")) + "。",
        "- PR本文の参照行: " + _code(policy["issue_reference"]["pr_body_line"].replace("{issue}", "<issue番号>")) + "。",
        "- 同じ参照は重複追加せず、件名・タイトル末尾の番号がブランチと異なる場合は拒否する。",
        "- PR本文にある別issueへの参照は保持する。",
        "- `no-issue`では自動補完しない。",
        "- 自動補完では自動クローズ用キーワードを使わない。自動クローズは明示指定時だけ扱う。",
        "- CIでは検証だけを行い、内容を書き換えない。",
        "- 過去のコミット参照を現在のPRブランチ番号へ一律に合わせない。",
        "", "## 機械検証用パターン", "",
        "type一覧を展開したPython正規表現です。issue接尾辞を先に分離してから全文一致で評価し、summary末尾とscopeの条件を別途適用します。", "",
    ])
    for label, field in (("コミット件名・PRタイトル", "subject_pattern"), ("ブランチ名", "branch_pattern")):
        lines.extend([label + ":", "", "```text",
                      compile_pattern(policy[field], names).pattern, "```", ""])
    lines.extend(["## 意味の判断が必要な指示", ""])
    lines.extend(["- " + value for value in policy["guidance"]] or ["利用先固有の追加指示はありません。"])
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--shared", type=Path, required=True)
    parser.add_argument("--local", type=Path)
    parser.add_argument("--output", required=True, help="Markdown path, or - for UTF-8 stdout")
    parser.add_argument("--check", action="store_true", help="Check an existing file without writing")
    args = parser.parse_args()
    try:
        document = render_document(load_policy(args.shared, args.local))
        if args.output == "-":
            if args.check:
                raise PolicyError("--check requires a file output")
            sys.stdout.buffer.write(document.encode("utf-8"))
        else:
            output = Path(args.output)
            inputs = [args.shared] + ([args.local] if args.local is not None else [])
            if any(output.resolve() == path.resolve() for path in inputs):
                raise PolicyError("output must not overwrite a configuration file")
            if args.check:
                if output.read_bytes() != document.encode("utf-8"):
                    raise PolicyError(f"{output}: generated document is out of date")
            else:
                output.write_bytes(document.encode("utf-8"))
    except (PolicyError, OSError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
